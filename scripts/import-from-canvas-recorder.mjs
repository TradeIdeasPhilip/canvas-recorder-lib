/**
 * Copy the player, and everything it imports, from canvas-recorder into this library.
 *
 * canvas-recorder is the source of truth.  This script throws away `dev/` and `src/` here and
 * copies them again, verbatim, so the library can be rebuilt from scratch at any time.
 *
 * Usage:  npm run import [-- path/to/canvas-recorder]
 *
 * The usual workflow:
 * 1. On a new branch, run this and commit the result as "Verbatim import from canvas-recorder <hash>".
 * 2. Rebase the library's hand edits (the commits after the previous verbatim import) onto it.
 *
 * Files are found by following relative imports, starting from `dev/canvas-recorder.ts`.
 * `src/dynamic-exports.ts` (the list of every video) is left out on purpose, and with it every video.
 */

import { execSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = resolve(here, process.argv[2] ?? "../canvas-recorder");

/** Where to start following imports. */
const ROOTS = ["dev/canvas-recorder.ts"];
/** Never copy these, and never follow their imports. */
const EXCLUDE = new Set(["src/dynamic-exports.ts"]);
/** Copied as is, even though nothing imports them. */
const EXTRAS = ["internals.md", "src/peano-fourier/fft-js.d.ts"];
/** The folders this script owns.  Everything in them is replaced on each import. */
const OWNED = ["dev", "src"];

// MARK: Find the files

const IMPORT_PATTERNS = [
  // import ... from "x";  export ... from "x";  (including multi-line braces)
  /\b(?:import|export)\s[^'"`;]*?\bfrom\s*["']([^"']+)["']/g,
  // import "x";
  /\bimport\s*["']([^"']+)["']/g,
  // import("x")
  /\bimport\(\s*["']([^"']+)["']\s*\)/g,
];
const CSS_IMPORT_PATTERN = /@import\s+(?:url\(\s*)?["']?([^"')\s;]+)["']?/g;

/** @param {string} file relative to `source` */
function specifiersIn(file) {
  const text = readFileSync(join(source, file), "utf8");
  const patterns = file.endsWith(".css") ? [CSS_IMPORT_PATTERN] : IMPORT_PATTERNS;
  const result = [];
  for (const pattern of patterns) {
    for (const match of text.matchAll(pattern)) {
      result.push(match[1]);
    }
  }
  return result.filter((specifier) => specifier.startsWith("."));
}

/**
 * @param {string} fromFile relative to `source`
 * @param {string} specifier a relative import
 * @returns the file relative to `source`, or undefined if it can't be found
 */
function resolveImport(fromFile, specifier) {
  const base = join(dirname(fromFile), specifier);
  for (const candidate of [base, base + ".ts", join(base, "index.ts")]) {
    const full = join(source, candidate);
    if (existsSync(full) && statSync(full).isFile()) {
      return relative(source, full);
    }
  }
  return undefined;
}

const found = new Set();
const missing = [];
const toVisit = [...ROOTS];
while (toVisit.length > 0) {
  const file = toVisit.pop();
  if (found.has(file) || EXCLUDE.has(file)) {
    continue;
  }
  found.add(file);
  if (!/\.(ts|css)$/.test(file)) {
    continue;
  }
  for (const specifier of specifiersIn(file)) {
    const target = resolveImport(file, specifier);
    if (target === undefined) {
      missing.push(`${file}: ${specifier}`);
    } else {
      toVisit.push(target);
    }
  }
}

// MARK: Copy them

for (const folder of OWNED) {
  rmSync(join(here, folder), { recursive: true, force: true });
}
const files = [...found, ...EXTRAS].sort();
for (const file of files) {
  const outside = !OWNED.some((folder) => file.startsWith(folder + "/"));
  if (outside && !EXTRAS.includes(file)) {
    throw new Error(`${file} is outside of ${OWNED.join(" and ")}.  Add a folder to OWNED.`);
  }
  mkdirSync(dirname(join(here, file)), { recursive: true });
  copyFileSync(join(source, file), join(here, file));
}

// MARK: The player's HTML

// The player expects all of these elements to exist when it starts.
// canvasRecorder.start() puts them in the page, so the main program's HTML can be empty.
const html = readFileSync(join(source, "canvas-recorder.html"), "utf8");
const body = /<body[^>]*>([\s\S]*)<\/body>/.exec(html);
if (!body) {
  throw new Error("No <body> in canvas-recorder.html");
}
const escaped = body[1].replaceAll("\\", "\\\\").replaceAll("`", "\\`").replaceAll("${", "\\${");
writeFileSync(
  join(here, "dev/player-body.ts"),
  `// Generated by scripts/import-from-canvas-recorder.mjs from canvas-recorder.html.  Do not edit.

/** The contents of the player's \`<body>\`.  {@link canvasRecorder.start} puts this in the page. */
export const playerBodyHtml = \`${escaped}\`;
`,
);
files.push("dev/player-body.ts");

// MARK: Report

let commit = "unknown";
try {
  commit = execSync("git rev-parse HEAD", { cwd: source, encoding: "utf8" }).trim();
  const dirty = execSync("git status --porcelain -- dev src canvas-recorder.html internals.md", {
    cwd: source,
    encoding: "utf8",
  }).trim();
  if (dirty) {
    commit += " (plus uncommitted changes)";
  }
} catch {
  // Not a git repository.  That's fine.
}
writeFileSync(
  join(here, "imported-files.txt"),
  `Copied from ${source}\nCommit ${commit}\n\n${files.sort().join("\n")}\n`,
);
console.log(`Copied ${files.length} files from ${source} at ${commit}.`);
if (missing.length > 0) {
  console.warn(`Could not resolve ${missing.length} imports:\n  ${missing.join("\n  ")}`);
}
